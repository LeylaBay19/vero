"""Models of the registration paths presented by the stand and archived UX."""
from copy import deepcopy
from auth_v1_diagrams import MODELS, edge, model, node


def revised_letter_models():
    models = deepcopy(MODELS)
    email = next(m for m in models if m['id'] == 'AUTH1_EMAIL')
    email['goal'] = 'Подтвердить почту руководителя и создать аккаунт перед подключением организации.'
    for step in email['nodes']:
        if step['row'] >= 2:
            step['row'] += 1
            step['y'] += 190
    email['nodes'].extend([
        node('existing', 'Аккаунт уже существует?', 1, 2, 'gateway', 'Платформа'),
        node('warning', 'Показать предупреждение и варианты действий', 2, 2, role='Платформа'),
        node('choice', 'Войти с этим email?', 2, 3, 'gateway'),
        node('login', 'Перейти ко входу с этим email', 2, 4, 'end'),
    ])
    email['edges'][1:2] = [
        edge('email', 'existing'), edge('existing', 'mail', 'Нет'),
        edge('existing', 'warning', 'Да'), edge('warning', 'choice'),
        edge('choice', 'login', 'Да'), edge('choice', 'email', 'Изменить email', 'right'),
    ]
    email['notes'].insert(0, 'Для занятого email письмо регистрации не отправляется. Можно войти с этим адресом или указать другой.')

    invite = next(m for m in models if m['id'] == 'AUTH1_INVITE')
    for step in invite['nodes']:
        if step['id'] == 'account':
            step.update(text='Есть аккаунт с email приглашения?', role='Платформа')
        elif step['id'] == 'new_password':
            step['text'] = 'Задать пароль и нажать «Присоединиться в качестве сотрудника»'
    invite['notes'].insert(1, 'Для входа в аккаунт с другим email используется схема «Приглашение на другую почту».')
    models.insert(models.index(invite)+1, model(
        'AUTH1_INVITE_OTHER', 'Приглашение на другую почту',
        'Добавить организацию в существующий аккаунт после проверки почты приглашения.',
        [
            node('start', 'Открыть приглашение', 1, 0, 'start'),
            node('login', 'Войти в свой аккаунт ВЕРО', 1, 1),
            node('send', 'Отправить код на почту приглашения', 1, 2, role='Платформа'),
            node('code', 'Ввести код из письма', 1, 3),
            node('valid', 'Код верный?', 1, 4, 'gateway', 'Платформа'),
            node('retry', 'Проверить код или запросить новый', 2, 4),
            node('confirm', 'Подтвердить присоединение к организации', 1, 5),
            node('assign', 'Добавить доступ к компании в этот аккаунт', 1, 6, role='Платформа'),
            node('done', 'В аккаунте доступна новая организация', 1, 7, 'end'),
        ],
        [
            edge('start', 'login'), edge('login', 'send'), edge('send', 'code'),
            edge('code', 'valid'), edge('valid', 'confirm', 'Да'), edge('valid', 'retry', 'Нет'),
            edge('retry', 'code', 'Повторить ввод', 'right'),
            edge('confirm', 'assign'), edge('assign', 'done'),
        ],
        [
            'Вход подтверждает аккаунт ВЕРО. Код подтверждает доступ к адресу приглашения. Логин ВЕРО остаётся прежним.',
            'Новый код заменяет предыдущий. Доступ появляется после явного подтверждения присоединения.',
            'Ранее подключённые компании и роли сохраняются. При повторном входе принятое приглашение не создаёт второе назначение.',
        ],
    ))
    return models


LETTER = revised_letter_models()


def process(key, title, goal, nodes, edges, notes=()):
    return dict(
        model(key, title, goal, [node(*n) for n in nodes], [edge(*e) for e in edges], notes),
        variant='UX-правки' if key.startswith('UX_') else 'по ТЗ',
    )


